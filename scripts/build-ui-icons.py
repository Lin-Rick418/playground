"""Build the original UI icon font. Build-only dependency: fonttools[woff]==4.60.2.

Run from any directory: python scripts/build-ui-icons.py
The committed WOFF2 is served locally; Python is not required by the app build.
"""

import json
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path

root = Path(__file__).resolve().parents[1]
source = root / "apps/web/src/assets/ui-icons.json"
paths = json.loads(source.read_text())
order = [".notdef", *paths]
font = FontBuilder(1000, isTTF=True)
font.setupGlyphOrder(order)
font.setupCharacterMap({0xE001 + i: name for i, name in enumerate(paths)})
glyphs = {}
for name in order:
    pen = TTGlyphPen(None)
    if name in paths:
        parse_path(paths[name], TransformPen(Cu2QuPen(pen, 1), (40, 0, 0, -40, 20, 960)))
    glyphs[name] = pen.glyph()
font.setupGlyf(glyphs)
# Keep the design-space left bearing: zero shifts every outline to the left.
font.setupHorizontalMetrics({name: (1000, getattr(glyphs[name], "xMin", 0)) for name in order})
font.setupHorizontalHeader(ascent=960, descent=-40)
font.setupNameTable({
    "familyName": "Casino UI Icons",
    "styleName": "Regular",
    "uniqueFontIdentifier": "Casino UI Icons 1.0",
    "fullName": "Casino UI Icons",
    "psName": "CasinoUIIcons",
    "version": "Version 1.0",
    "copyright": "Original project UI artwork. No external icon assets.",
})
font.setupOS2(version=4, sTypoAscender=960, sTypoDescender=-40, sTypoLineGap=0, usWinAscent=960, usWinDescent=40, fsSelection=0xC0)
font.setupPost()
font.setupMaxp()
font.font["head"].created = font.font["head"].modified = 2082844800
font.font.recalcTimestamp = False
font.font.flavor = "woff2"
font.save(root / "apps/web/src/assets/ui-icons.woff2")
mapping = "// Generated by scripts/build-ui-icons.py; edit assets/ui-icons.json.\n"
mapping += "export const iconGlyphs = {\n"
mapping += "".join(f'  "{name}": "\\u{0xE001 + i:04x}",\n' for i, name in enumerate(paths))
mapping += "} as const;\nexport type IconName = keyof typeof iconGlyphs;\n"
(root / "apps/web/src/lib/ui-icons.ts").write_text(mapping)
print(f"Built {len(paths)} original icons.")
